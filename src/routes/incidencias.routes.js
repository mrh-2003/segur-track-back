'use strict';
const {Router}=require('express'),ctrl=require('../controllers/incidencias.controller'),v=require('../validators/incidencias.validator');
const {validar}=require('../middlewares/validar'),{autorizar}=require('../middlewares/auth');
const router=Router(),operar=autorizar('administrador','jefe_operaciones','operador');
router.param('id',require('../middlewares/identificador'));router.param('solicitudId',require('../middlewares/identificador'));
router.get('/',ctrl.listar);router.get('/resumen',ctrl.resumen);router.get('/recientes',ctrl.recientes);router.get('/tipos',ctrl.listarTipos);router.get('/responsables',ctrl.responsables);router.get('/:id',ctrl.obtener);
router.post('/',validar(v.esquemaCrear),ctrl.crear);
router.put('/:id',autorizar('administrador','jefe_operaciones','supervisor'),validar(v.esquemaActualizar),ctrl.actualizar);
router.patch('/:id/responsable',autorizar('administrador','jefe_operaciones','supervisor'),validar(require('zod').z.object({responsableId:require('zod').z.number().int().positive()})),ctrl.asignar);
router.post('/:id/acciones',operar,validar(v.esquemaAccion),ctrl.actuar);
router.post('/:id/ampliaciones',autorizar('supervisor'),validar(v.esquemaSolicitud),ctrl.solicitar);
router.patch('/:id/ampliaciones/:solicitudId',autorizar('jefe_operaciones'),validar(v.esquemaDecision),ctrl.decidir);
router.patch('/:id/estado',operar,validar(v.esquemaCambiarEstado),ctrl.cambiarEstado);
router.patch('/:id/observacion',operar,validar(v.esquemaObservacion),ctrl.registrarObservacion);
router.delete('/:id',autorizar('administrador','jefe_operaciones'),ctrl.eliminar);
module.exports=router;
